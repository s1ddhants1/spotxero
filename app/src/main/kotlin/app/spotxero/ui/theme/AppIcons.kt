    private fun iconFromPathData(
        name: String,
        pathData: String,
        viewportWidth: Float = 960f,
        viewportHeight: Float = 960f
    ): ImageVector {
        return ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = viewportWidth,
            viewportHeight = viewportHeight
        ).apply {
            addPath(
                pathData = addPathNodes(pathData),
                fill = SolidColor(Color.Black)
            )
        }.build()
    }

    private fun materialSymbol(
        name: String,
        pathData: String,
    ): ImageVector {
        return ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 960f,
            viewportHeight = 960f
        ).apply {
            addGroup(translationY = 960f)
            addPath(
                pathData = addPathNodes(pathData),
                fill = SolidColor(Color.Black)
            )
            clearGroup()
        }.build()
    }

